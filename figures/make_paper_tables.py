#!/usr/bin/env python3
"""Generate LaTeX tables and number macros from the saved paper evidence.

Reads only results/*/data and analysis/tables. Writes:
  tables/tab_conditions.tex, tables/tab_families.tex, tables/tab_references.tex, numbers.tex
Every number quoted in the manuscript text should come from a macro in numbers.tex.
"""
from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd

ENVS = {"lunarlander": "LL", "minatar": "MA"}
ENV_NAME = {"lunarlander": "LunarLander", "minatar": "MinAtar Breakout"}
DEC = {"lunarlander": 1, "minatar": 2}
TNAME = {0.0: "zero", 0.25: "quarter", 0.5: "half", 0.75: "threeq", 1.0: "one"}
COND_ORDER = ["full_classical", "H(0)", "H(0.25)", "H(0.5)", "H(0.75)", "H(1)", "C(0)", "C(0.25)", "C(0.5)", "C(0.75)"]


def cond_tex(c: str) -> str:
    return "Full classical" if c == "full_classical" else c.replace("(", "($").replace(")", "$)").replace("$0", "0").replace("($", "(").replace("$)", ")")


def cond_id(c: str) -> str:
    if c == "full_classical":
        return "FC"
    head, t = c[0], float(c[2:-1])
    return f"{head}{TNAME[t]}"


def num(x: float, d: int) -> str:
    s = f"{x:.{d}f}"
    return s.replace("-", "$-$") if s.startswith("-") else s


def pval(p: float) -> str:
    return "$<$0.001" if p < 0.001 else f"{p:.3f}"


class Macros:
    def __init__(self):
        self.lines = ["% Auto-generated by make_paper_tables.py from public paper evidence surface. Do not edit by hand."]

    def add(self, name: str, value: str) -> None:
        assert name.isalpha(), name
        self.lines.append(f"\\newcommand{{\\{name}}}{{{value}}}")


def contrast_id(c: str) -> str:
    left, right = [x.strip() for x in c.replace("_", " ").split(" - ")]
    f = lambda x: {"full classical": "FC", "teacher": "Teacher"}.get(x, cond_id(x) if x[0] in "HC" else x)
    return f"{f(left)}Vs{f(right)}"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", type=Path, default=Path("."))
    ap.add_argument("--out", type=Path, required=True)
    a = ap.parse_args()
    ae = lambda e, f: pd.read_csv(a.root / "analysis/tables" / e / f)
    at = lambda f: pd.read_csv(a.root / "analysis/tables" / f)
    cs, fcr, crc, res = at("condition_summary.csv"), at("fc_reference_contrasts.csv"), at("continuation_reference_contrasts.csv"), at("resource_breakdown.csv")
    timing = at("minatar_serial_timing.csv").set_index("condition")
    m = Macros()
    (a.out / "tables").mkdir(parents=True, exist_ok=True)

    # ---------------- Table: conditions
    rows = []
    for env, pre in ENVS.items():
        d = DEC[env]
        rows.append(f"\\multicolumn{{6}}{{l}}{{\\textit{{{ENV_NAME[env]}}}}}\\\\")
        sub = cs[cs.environment == env].set_index("condition")
        h0q = sub.loc["H(0)", "mean_qforward_total"]
        for c in COND_ORDER:
            r = sub.loc[c]
            rows.append(f"{cond_tex(c)} & {int(r.n)} & {num(r.mean_final_return, d)} $\\pm$ {num(r.sd_final_return, d)} & "
                        f"{num(r.iqm_final_return, d)} & {r.mean_qforward_total / 1e6:.2f} & {r.total_env_interactions / 1e6:.3f}\\\\")
            cid = cond_id(c)
            m.add(f"Num{pre}Mean{cid}", num(r.mean_final_return, d))
            m.add(f"Num{pre}SD{cid}", num(r.sd_final_return, d))
            if c.startswith("H"):
                m.add(f"Num{pre}Qfwd{cid}", f"{r.mean_qforward_total / 1e6:.1f}")
                m.add(f"Num{pre}PctOfHzero{cid}", f"{100 * r.mean_final_return / sub.loc['H(0)', 'mean_final_return']:.1f}")
                if c != "H(0)":
                    ch = 100 * (r.mean_qforward_total / h0q - 1)
                    m.add(f"Num{pre}QfwdChange{cid}", f"{ch:+.0f}".replace("-", "$-$"))
        rows.append("\\midrule")
    rows = rows[:-1]
    (a.out / "tables/tab_conditions.tex").write_text(
        "\\begin{tabular}{@{}lrrrrr@{}}\n\\toprule\n"
        "Condition & $n$ & Mean $\\pm$ SD & IQM & Q-forwards (M) & Env. interactions (M)\\\\\n\\midrule\n"
        + "\n".join(rows) + "\n\\botrule\n\\end{tabular}\n")

    # ---------------- Table: preregistered families
    rows = []
    for env, pre in ENVS.items():
        d = DEC[env]
        for fam, f in (("Allocation (RQ1)", "rq1_allocation.csv"), ("Attribution (RQ2)", "rq2_attribution.csv")):
            t = ae(env, f)
            pcol = [c for c in t.columns if c.startswith("sign_flip")][0]
            rows.append(f"\\multicolumn{{5}}{{l}}{{\\textit{{{ENV_NAME[env]} --- {fam}}}}}\\\\")
            for _, r in t.iterrows():
                rows.append(f"{r.contrast.replace(' - ', ' $-$ ')} & {num(r.paired_mean_difference, d)} & "
                            f"[{num(r.ci95_low, d)}, {num(r.ci95_high, d)}] & {pval(r[pcol])} & {pval(r.holm_p)}\\\\")
                cid = contrast_id(r.contrast)
                for k, v in (("Delta", num(r.paired_mean_difference, d)), ("Lo", num(r.ci95_low, d)),
                             ("Hi", num(r.ci95_high, d)), ("P", pval(r[pcol])), ("Holm", pval(r.holm_p))):
                    m.add(f"Num{pre}{cid}{k}", v)
            rows.append("\\midrule")
    rows = rows[:-1]
    (a.out / "tables/tab_families.tex").write_text(
        "\\begin{tabular}{@{}lrlrr@{}}\n\\toprule\n"
        "Contrast & $\\Delta$ & 95\\% CI & $p$ & $p_{\\mathrm{Holm}}$\\\\\n\\midrule\n"
        + "\n".join(rows) + "\n\\botrule\n\\end{tabular}\n")

    # ---------------- Table: descriptive references
    rows = []
    for env, pre in ENVS.items():
        d = DEC[env]
        rows.append(f"\\multicolumn{{5}}{{l}}{{\\textit{{{ENV_NAME[env]}}}}}\\\\")
        t = fcr[fcr.environment == env]
        pcol = [c for c in t.columns if c.startswith("sign_flip")][0]
        for _, r in t.iterrows():
            label = r.contrast.replace("full_classical", "Full classical").replace(" - ", " $-$ ")
            rows.append(f"{label} & {num(r.paired_mean_difference, d)} & [{num(r.ci95_low, d)}, {num(r.ci95_high, d)}] & "
                        f"{pval(r[pcol])} & --\\\\")
            cid = contrast_id(r.contrast)
            for k, v in (("Delta", num(r.paired_mean_difference, d)), ("Lo", num(r.ci95_low, d)),
                         ("Hi", num(r.ci95_high, d)), ("P", pval(r[pcol]))):
                m.add(f"Num{pre}{cid}{k}", v)
            if r.contrast == "H(1) - teacher":
                m.add(f"Num{pre}RetentionHone", f"{r.retention_pct_of_teacher_mean:.1f}")
                m.add(f"Num{pre}PearsonHone", f"{r.pearson_r_same_seed:.3f}")
        tc = crc[crc.environment == env]
        pcol = [c for c in tc.columns if c.startswith("sign_flip")][0]
        for _, r in tc.iterrows():
            right = f"{r.right_head}({r.handoff_t:g})"
            rows.append(f"Full classical $-$ {right} & {num(r.paired_mean_difference, d)} & "
                        f"[{num(r.ci95_low, d)}, {num(r.ci95_high, d)}] & {pval(r[pcol])} & {int(r.wins_classical)}/20\\\\")
            cid = f"FCVs{r.right_head}{TNAME[r.handoff_t]}"
            for k, v in (("Delta", num(r.paired_mean_difference, d)), ("Lo", num(r.ci95_low, d)),
                         ("Hi", num(r.ci95_high, d)), ("P", pval(r[pcol]))):
                m.add(f"Num{pre}{cid}{k}", v)
        rows.append("\\midrule")
    rows = rows[:-1]
    (a.out / "tables/tab_references.tex").write_text(
        "\\begin{tabular}{@{}lrlrr@{}}\n\\toprule\n"
        "Contrast & $\\Delta$ & 95\\% CI & $p$ (unadj.) & Wins\\\\\n\\midrule\n"
        + "\n".join(rows) + "\n\\botrule\n\\end{tabular}\n")

    # ---------------- RQ3 and timing macros
    for env, pre in ENVS.items():
        d = DEC[env]
        t3 = ae(env, "rq3_decomposition.csv").set_index("handoff_t")
        for t in (0.25, 0.5, 0.75):
            for col, key in (("post_kd_gap_h_minus_c", "PostKDGap"), ("hybrid_online_gain", "OnlineH"),
                             ("classical_online_gain", "OnlineC"), ("online_gain_interaction_I", "Interaction")):
                for suf, k in (("mean", ""), ("ci95_low", "Lo"), ("ci95_high", "Hi")):
                    m.add(f"Num{pre}{key}{TNAME[t]}{k}", num(t3.loc[t, f"{col}_{suf}"], d))
    wall = lambda c: (timing.loc[c, "kd_wall_clock_mean_seconds"] + timing.loc[c, "online_wall_clock_mean_seconds"]) / 3600
    m.add("NumMAWallHzero", f"{wall('H(0)'):.2f}")
    m.add("NumMAWallCzero", f"{wall('C(0)'):.2f}")
    m.add("NumMAWallRatio", f"{wall('H(0)') / wall('C(0)'):.0f}")
    m.add("NumMAEnergyRatio", f"{timing.loc['H(0)', 'combined_energy_mean_kwh'] / timing.loc['C(0)', 'combined_energy_mean_kwh']:.0f}")
    for env, pre in ENVS.items():
        sub = cs[cs.environment == env].set_index("condition")
        base, staged = sub.loc["H(0)", "total_env_interactions"], sub.loc["H(0.5)", "total_env_interactions"]
        m.add(f"Num{pre}ExtraInteractionsPct", f"{100 * (staged / base - 1):.1f}")
        m.add(f"Num{pre}ExtraInteractions", f"{int(staged - base):,}")
    (a.out / "numbers.tex").write_text("\n".join(m.lines) + "\n")
    print(f"{len(m.lines) - 1} macros")


if __name__ == "__main__":
    main()
